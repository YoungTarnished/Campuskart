const express = require('express')
const validate = require('../middleware/validate')
const { protect, optionalAuth, requireVerified, requireRole } = require('../middleware/auth')
const { authLimiter, bidLimiter } = require('../middleware/rateLimit')
const upload = require('../middleware/upload')
const schemas = require('../validators/schemas')

const auth = require('../controllers/authController')
const products = require('../controllers/productController')
const orders = require('../controllers/orderController')
const auctions = require('../controllers/auctionController')
const services = require('../controllers/serviceController')
const exchanges = require('../controllers/exchangeController')
const chat = require('../controllers/chatController')
const notifications = require('../controllers/notificationController')
const reviews = require('../controllers/reviewController')
const reports = require('../controllers/reportController')
const admin = require('../controllers/adminController')
const users = require('../controllers/userController')
const uploads = require('../controllers/uploadController')

const router = express.Router()
const adminOnly = [protect, requireRole('admin')]

router.post('/auth/register', authLimiter, validate(schemas.registerSchema), auth.register)
router.post('/auth/login', authLimiter, validate(schemas.loginSchema), auth.login)
router.post('/auth/logout', protect, auth.logout)
router.get('/auth/me', protect, auth.me)
router.put('/auth/profile', protect, validate(schemas.profileSchema), auth.updateProfile)
router.post('/auth/verify-email', validate(schemas.verifySchema), auth.verifyEmail)
router.post('/auth/resend-verification', protect, auth.resendVerification)
router.post('/auth/forgot-password', authLimiter, validate(schemas.forgotSchema), auth.forgotPassword)
router.post('/auth/reset-password', validate(schemas.resetSchema), auth.resetPassword)

router.get('/products/deals', products.deals)
router.get('/products/recommendations', protect, products.recommendations)
router.get('/products/recent', protect, products.recent)
router.get('/products/me', protect, products.mine)
router.post('/products/price-suggestion', protect, validate(schemas.priceSuggestionSchema), products.priceSuggestion)
router.get('/products', validate(schemas.productQuerySchema), products.list)
router.post('/products', protect, requireVerified, validate(schemas.productSchema), products.create)
router.get('/products/:id', optionalAuth, validate(schemas.idParams), products.getOne)
router.put('/products/:id', protect, requireVerified, validate(schemas.productSchema), products.update)
router.delete('/products/:id', protect, requireVerified, validate(schemas.idParams), products.remove)

router.get('/wishlist', protect, users.wishlist)
router.post('/wishlist/:productId', protect, users.addWish)
router.delete('/wishlist/:productId', protect, users.removeWish)

router.get('/orders/purchases', protect, orders.purchases)
router.get('/orders/sales', protect, orders.sales)
router.post('/orders', protect, requireVerified, validate(schemas.orderCreateSchema), orders.create)
router.get('/orders/:id', protect, validate(schemas.idParams), orders.getOne)
router.patch('/orders/:id/accept', protect, validate(schemas.idParams), orders.accept)
router.patch('/orders/:id/reject', protect, validate(schemas.idParams), orders.reject)
router.patch('/orders/:id/cancel', protect, validate(schemas.idParams), orders.cancel)
router.patch('/orders/:id/confirm-payment', protect, validate(schemas.idParams), orders.confirm)

router.get('/auctions/me', protect, auctions.mine)
router.get('/auctions', auctions.list)
router.post('/auctions', protect, requireVerified, validate(schemas.auctionSchema), auctions.create)
router.get('/auctions/:id', optionalAuth, validate(schemas.idParams), auctions.getOne)
router.put('/auctions/:id', protect, requireVerified, validate(schemas.auctionSchema), auctions.update)
router.delete('/auctions/:id', protect, requireVerified, validate(schemas.idParams), auctions.remove)
router.patch('/auctions/:id/cancel', protect, validate(schemas.idParams), auctions.cancel)
router.post('/auctions/:id/bids', bidLimiter, protect, requireVerified, validate(schemas.bidSchema), auctions.bid)
router.post('/auctions/:id/watch', protect, validate(schemas.idParams), auctions.watch)
router.delete('/auctions/:id/watch', protect, validate(schemas.idParams), auctions.unwatch)

router.get('/services/requests/incoming', protect, services.incoming)
router.get('/services/requests/outgoing', protect, services.outgoing)
router.patch('/services/requests/:id/accept', protect, validate(schemas.idParams), services.acceptRequest)
router.patch('/services/requests/:id/reject', protect, validate(schemas.idParams), services.rejectRequest)
router.patch('/services/requests/:id/cancel', protect, validate(schemas.idParams), services.cancelRequest)
router.patch('/services/requests/:id/complete', protect, validate(schemas.idParams), services.completeRequest)
router.get('/services/me', protect, services.mine)
router.get('/services', services.list)
router.post('/services', protect, requireVerified, validate(schemas.serviceSchema), services.create)
router.get('/services/:id', validate(schemas.idParams), services.getOne)
router.put('/services/:id', protect, requireVerified, validate(schemas.serviceSchema), services.update)
router.delete('/services/:id', protect, requireVerified, validate(schemas.idParams), services.remove)
router.post('/services/:id/requests', protect, requireVerified, validate(schemas.serviceRequestSchema), services.requestService)

router.get('/exchanges', protect, exchanges.list)
router.post('/exchanges', protect, requireVerified, validate(schemas.exchangeSchema), exchanges.create)
router.patch('/exchanges/:id/accept', protect, validate(schemas.idParams), exchanges.accept)
router.patch('/exchanges/:id/reject', protect, validate(schemas.idParams), exchanges.reject)
router.patch('/exchanges/:id/cancel', protect, validate(schemas.idParams), exchanges.cancel)

router.get('/conversations', protect, chat.list)
router.post('/conversations', protect, validate(schemas.conversationSchema), chat.create)
router.get('/conversations/:id/messages', protect, validate(schemas.idParams), chat.messages)
router.post('/conversations/:id/messages', protect, validate(schemas.messageSchema), chat.send)

router.get('/notifications/unread-count', protect, notifications.unreadCount)
router.get('/notifications', protect, notifications.list)
router.patch('/notifications/read-all', protect, notifications.markAll)
router.patch('/notifications/:id/read', protect, validate(schemas.idParams), notifications.markRead)

router.post('/reviews', protect, requireVerified, validate(schemas.reviewSchema), reviews.create)
router.get('/reviews/user/:id', validate(schemas.idParams), reviews.forUser)

router.post('/reports', protect, validate(schemas.reportSchema), reports.createReport)
router.get('/reports', protect, reports.myReports)
router.post('/disputes', protect, validate(schemas.disputeSchema), reports.createDispute)
router.get('/disputes', protect, reports.myDisputes)

router.get('/dashboard', protect, users.dashboard)
router.get('/users/:id', validate(schemas.idParams), users.publicProfile)

router.get('/uploads/storage', uploads.storage)
router.post('/uploads', protect, upload.array('images', 5), uploads.uploadImages)

router.get('/admin/stats', ...adminOnly, admin.stats)
router.get('/admin/users', ...adminOnly, admin.users)
router.patch('/admin/users/:id', ...adminOnly, validate(schemas.adminUserSchema), admin.setSuspension)
router.patch('/admin/products/:id/remove', ...adminOnly, validate(schemas.idParams), admin.removeProduct)
router.patch('/admin/services/:id/remove', ...adminOnly, validate(schemas.idParams), admin.removeService)
router.patch('/admin/auctions/:id/remove', ...adminOnly, validate(schemas.idParams), admin.removeAuction)
router.get('/admin/reports', ...adminOnly, admin.reports)
router.patch('/admin/reports/:id', ...adminOnly, validate(schemas.resolveReportSchema), admin.resolveReport)
router.get('/admin/disputes', ...adminOnly, admin.disputes)
router.patch('/admin/disputes/:id', ...adminOnly, validate(schemas.resolveDisputeSchema), admin.resolveDispute)

module.exports = router
